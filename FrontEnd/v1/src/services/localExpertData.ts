export function getLocalExpertFallback(text: string, destination: string): string {
  const isJeju = destination.includes('제주');
  const isGyeongju = destination.includes('경주');
  const isGangneung = destination.includes('강릉') || destination.includes('속초') || destination.includes('동해');
  const isBusan = destination.includes('부산');

  const lower = text.toLowerCase();

  if (lower.includes('에티켓') || lower.includes('식사') || lower.includes('예절') || lower.includes('식당') || lower.includes('맛집')) {
    if (isJeju) {
      return `제주 향토 식당(보말, 몸국, 갈치조림 등)이나 해녀의 집 방문 시, 지역 어르신(삼춘)들께서 운영하시는 곳이 많아 점심 피크(12:00~13:30) 전후로 방문하시면 한결 여유롭게 대접받으실 수 있습니다. 또한 흑돼지 전문점은 전문 그릴링 직원이 최적의 타이밍으로 구워주므로 임의로 자주 뒤집지 않는 것이 육즙을 보존하는 로컬 에티켓입니다. 해변가 식당 입장 시에는 입구에서 신발의 바닷모래를 가볍게 털어주시는 센스가 환영받습니다.`;
    }
    if (isGyeongju) {
      return `경주 황리단길 및 교촌마을 일대 식당들은 주말 브레이크 타임(15:00~17:00)이 엄격한 편이며, 전통 한옥 고택을 개조한 곳이 많아 툇마루 및 신발 보관 구역을 잘 확인하셔야 합니다. 문화재 보호구역 인근이므로 야외 취식 시 지정된 쓰레기 수거함 이용 및 역사 유적지 예절을 지켜주시는 것이 품격 있는 여행자의 기본입니다.`;
    }
    if (isGangneung) {
      return `강릉 초당 순두부 마을이나 중앙시장 회센터 방문 시, 주말 오전 11시 전 조기 방문하시는 것이 대기 시간을 크게 줄여줍니다. 초당 순두부는 담백한 몽글순두부 본연의 맛을 먼저 음미하신 후 양념장을 곁들이는 것이 전통 취식법이며, 강문·안목 해변 카페거리는 일몰 시 창가석 경쟁이 치열하므로 30분 일찍 자리 잡으시는 것을 추천합니다.`;
    }
    if (isBusan) {
      return `부산 자갈치 시장이나 민락회타운은 활어회 주문 후 2층 초장집에서 상차림비를 내고 드시는 문화가 정착되어 있습니다. 돼지국밥은 새우젓과 부추(정구지)를 넉넉히 넣어 기호에 맞게 간을 맞추어 드시는 것이 부산 토박이들의 정석 비법입니다.`;
    }
    return `${destination} 현지 식당은 지역 고유 식재료의 계절 특수성이 있으므로, 당일 추천 메뉴나 제철 반찬을 여쭈어보시면 훨씬 더 풍성한 미식을 즐기실 수 있습니다.`;
  }

  if (lower.includes('응급') || lower.includes('부상') || lower.includes('병원') || lower.includes('위급') || lower.includes('119') || lower.includes('사고')) {
    if (isJeju) {
      return `[🚨 제주 긴급 안심 비상망]\n• 24시간 제주대병원 권역응급의료센터: 064-717-1919 (제주시 아란13길 15)\n• 서귀포의료원 응급실: 064-730-3109 (서귀포시 장수로 47)\n• 제주해양경찰서 긴급구조: 122 / 화재·응급구조: 119\n• 길벗 AI 24시 SOS 전담 상황실: 1800-7233 (내선 1번)\n해안가나 오름 보행 중 부상 발생 시, 스마트폰 네이버/카카오 지도에서 현 위치 '주소 복사' 후 119에 전달하시면 가장 빠른 119 구급차가 급파됩니다.`;
    }
    if (isGyeongju) {
      return `[🚨 경주 긴급 안심 비상망]\n• 24시간 동국대학교 경주병원 권역응급의료센터: 054-770-8288 (경주시 동대로 87)\n• 경주소방서 119안전센터: 국번없이 119\n• 황남파출소(황리단길 관할): 054-772-2112\n• 길벗 AI 24시 SOS 긴급상황실: 1800-7233 (내선 2번)\n야간 유적지 보행 시 조명이 어두울 수 있으므로 손전등 앱을 켜고, 돌부리나 경사로 낙상 시 즉각 비상 연락망으로 지원을 요청하세요.`;
    }
    if (isGangneung) {
      return `[🚨 강원 영동권 긴급 비상망]\n• 24시간 강릉아산병원 권역응급의료센터: 033-610-3119 (강릉시 사천면 방동길 38)\n• 강릉소방서 구급대: 119 / 동해해양경찰서: 122\n• 길벗 AI 24시 SOS 지원팀: 1800-7233 (내선 3번)\n동해안 너울성 파도 경보 시 방파제 및 갯바위 출입을 즉시 삼가시고 안전지대로 이동하십시오.`;
    }
    return `[🚨 ${destination} 긴급 비상 대응망]\n• 전국 공통 24시간 소방 구급/화재: 국번없이 119\n• 경찰청 긴급범죄/안전신고: 국번없이 112\n• 길벗 AI 24시 핫라인: 1800-7233\n위급 상황 시 즉시 119 상황실에 현재 도로명 주소 또는 근처 큰 건물을 알려주시면 신속한 현장 출동 조치가 취해집니다.`;
  }

  if (lower.includes('포인트') || lower.includes('명소') || lower.includes('비경') || lower.includes('사진') || lower.includes('포토')) {
    if (isJeju) {
      return `제주 토박이 작가들이 극찬하는 숨은 사진 명소는 '군산오름 정상(차량으로 8부 능선까지 진입 가능)'의 한라산-바다 360도 파노라마 일몰뷰와, 애월 해안도로의 '가문동 포구' 방파제입니다. 특히 날씨가 맑은 날 해질녘 가문동 포구에서는 붉게 물든 하늘과 비양도 실루엣이 수채화처럼 어우러집니다.`;
    }
    if (isGyeongju) {
      return `경주 감성 포토존으로는 황리단길 인근 '황남동 고분군 일몰 실루엣'과 보문호수 '물너울교 야경'을 강력 추천합니다. 동궁과 월지보다 한산하면서도 고즈넉한 능선의 곡선과 물안개가 어우러져 한 폭의 한국화 같은 인생 사진을 남기실 수 있습니다.`;
    }
    if (isGangneung) {
      return `강릉에서는 정동진 헌화로 드라이브 코스의 해안 절벽 뷰와, 사천진 해변의 아담한 무인 교각 포토스팟을 추천합니다. 아침 해돋이 무렵 붉은 햇살이 백사장에 비칠 때 가장 영롱한 색감이 연출됩니다.`;
    }
    return `${destination} 여행의 참된 묘미는 유명 랜드마크뿐 아니라 골목길과 산책로에서 마주하는 자연스러운 순간에 있습니다. 일출 직후와 일몰 30분 전 '골든 아워'에 야외 명소를 방문하시면 가장 아름다운 채광의 사진을 담으실 수 있습니다.`;
  }

  if (lower.includes('문화') || lower.includes('풍습') || lower.includes('주의') || lower.includes('날씨') || lower.includes('준비물')) {
    if (isJeju) {
      return `제주는 해안과 중산간의 기온 차가 크고 바람이 잦으므로, 한여름이라도 가벼운 방풍 겉옷이나 얇은 스카프를 소지하시는 것이 좋습니다. 오름 탐방 시에는 진드기 방지 스프레이와 편안한 트레킹화를 권장하며, '정낭(대문 역할을 하는 세 개의 통나무)'의 위치에 따른 제주 전통 부재중 표시 문화를 이해하시면 여행이 한층 흥미로워집니다.`;
    }
    if (isGyeongju) {
      return `경주는 도시 전체가 지붕 없는 박물관입니다. 고분(능) 위로 올라가는 행위는 문화재보호법 위반이자 엄격한 과태료 대상이므로 정숙한 관람을 준수해야 합니다. 낮과 밤의 기온 차가 큰 분지형 기후이므로 저녁 야경 투어(동궁과 월지, 첨성대 등) 시 걸칠 수 있는 따뜻한 겉옷을 챙기시면 좋습니다.`;
    }
    return `${destination}의 계절별 기상 특성과 지형을 감안하여 편안한 보행용 신발과 일교차 대비용 겉옷을 준비하시면 더욱 쾌적하고 안전한 여행이 됩니다.`;
  }

  return `${destination} 여행은 여유로운 쉼과 지역 고유의 온기를 체감하는 소중한 시간입니다. 길벗 AI 12인 멀티에이전트가 검증한 무중복 동선과 안전 가이드를 신뢰하시고, 언제든 궁금한 점이 생기시면 편안하게 질문해 주세요!`;
}
